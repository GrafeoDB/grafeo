fn sanitize_module_name(path: &str) -> String {
    path.replace('/', "_")
        .replace(['.', '-', ' '], "_")
        .to_lowercase()
}

fn sanitize_test_name(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect::<String>()
        .to_lowercase()
}

fn escape_rust_string(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}

fn generate_tests(
    output: &mut String,
    file: &GtestFile,
    module_name: &str,
    rel_path: &str,
) -> usize {
    let mut count = 0;

    writeln!(output, "mod {module_name} {{").unwrap();
    writeln!(output, "    #[allow(unused_imports)]").unwrap();
    writeln!(output, "    use super::*;").unwrap();
    writeln!(output).unwrap();

    // Cases in text-index or vector-index spec files get an extra `_persistent`
    // variant so the WAL-wrapped store path (the one every `GrafeoDB::open()`
    // goes through) is exercised alongside the in-memory one. Index-aware
    // operators have historically diverged between the two paths (see #308).
    let file_needs_persistent = file
        .meta
        .requires
        .iter()
        .any(|r| r == "text-index" || r == "vector-index");

    for tc in &file.tests {
        // Skip tests with skip field
        if tc.skip.is_some() {
            writeln!(
                output,
                "    #[test]\n    #[ignore = \"skipped in .gtest\"]\n    fn {}() {{}}\n",
                sanitize_test_name(&tc.name)
            )
            .unwrap();
            count += 1;
            continue;
        }

        let case_needs_persistent = file_needs_persistent
            || tc
                .requires
                .iter()
                .any(|r| r == "text-index" || r == "vector-index");

        // Handle rosetta variants
        if !tc.variants.is_empty() {
            for (lang, query) in &tc.variants {
                let fn_name = format!(
                    "{}_{}",
                    sanitize_test_name(&tc.name),
                    sanitize_test_name(lang)
                );
                generate_single_test(
                    output,
                    &TestSpec {
                        fn_name: &fn_name,
                        file,
                        tc,
                        query_override: Some(query),
                        lang_override: Some(lang),
                        rel_path,
                        db_source: DbSource::InMemory,
                    },
                );
                count += 1;
                if case_needs_persistent {
                    generate_single_test(
                        output,
                        &TestSpec {
                            fn_name: &format!("{fn_name}_persistent"),
                            file,
                            tc,
                            query_override: Some(query),
                            lang_override: Some(lang),
                            rel_path,
                            db_source: DbSource::Persistent,
                        },
                    );
                    count += 1;
                }
            }
        } else {
            let base = sanitize_test_name(&tc.name);
            generate_single_test(
                output,
                &TestSpec {
                    fn_name: &base,
                    file,
                    tc,
                    query_override: None,
                    lang_override: None,
                    rel_path,
                    db_source: DbSource::InMemory,
                },
            );
            count += 1;
            if case_needs_persistent {
                generate_single_test(
                    output,
                    &TestSpec {
                        fn_name: &format!("{base}_persistent"),
                        file,
                        tc,
                        query_override: None,
                        lang_override: None,
                        rel_path,
                        db_source: DbSource::Persistent,
                    },
                );
                count += 1;
            }
        }
    }

    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();

    count
}

#[derive(Clone, Copy)]
enum DbSource {
    InMemory,
    Persistent,
}

struct TestSpec<'a> {
    fn_name: &'a str,
    file: &'a GtestFile,
    tc: &'a TestCase,
    query_override: Option<&'a str>,
    lang_override: Option<&'a str>,
    rel_path: &'a str,
    db_source: DbSource,
}

fn generate_single_test(output: &mut String, spec: &TestSpec<'_>) {
    let fn_name = spec.fn_name;
    let file = spec.file;
    let tc = spec.tc;
    let query_override = spec.query_override;
    let lang_override = spec.lang_override;
    let rel_path = spec.rel_path;
    let db_source = spec.db_source;
    let language = lang_override
        .or(tc.language.as_deref())
        .unwrap_or(&file.meta.language);
    let model = &file.meta.model;

    // Feature gate: languages that require specific feature flags.
    // graphql-rdf needs both "graphql" and "rdf" features.
    let feature_gates: Vec<&str> = match language {
        "cypher" => vec!["cypher"],
        "gremlin" => vec!["gremlin"],
        "graphql" => vec!["graphql"],
        "graphql-rdf" => vec!["graphql", "rdf"],
        "sparql" => vec!["sparql"],
        "sql-pgq" | "sql_pgq" => vec!["sql-pgq"],
        _ => vec![],
    };

    // Requires from file meta + per-test requires
    let mut all_requires: Vec<&str> = file.meta.requires.iter().map(String::as_str).collect();
    for req in &tc.requires {
        if !all_requires.contains(&req.as_str()) {
            all_requires.push(req);
        }
    }
    for fg in feature_gates {
        if !all_requires.contains(&fg) {
            all_requires.push(fg);
        }
    }

    // Only emit #[cfg] for known Cargo features. Binding capabilities
    // (e.g. "int64-safe") are not Cargo features and the Rust runner
    // always has full fidelity, so they pass through without gating.
    const CARGO_FEATURES: &[&str] = &[
        "gql",
        "cypher",
        "sparql",
        "gremlin",
        "graphql",
        "sql-pgq",
        "rdf",
        "algos",
        "vector-index",
        "text-index",
        "hybrid-search",
        "cdc",
        "tiered-storage",
        "succinct-indexes",
        "ring-index",
        "shacl",
        "block-stm",
        "wal",
        "spill",
        "mmap",
    ];
    let cargo_requires: Vec<&str> = all_requires
        .iter()
        .filter(|r| CARGO_FEATURES.contains(r))
        .copied()
        .collect();

    if !cargo_requires.is_empty() {
        let cfg_parts: Vec<String> = cargo_requires
            .iter()
            .map(|r| format!("feature = \"{r}\""))
            .collect();
        let cfg = if cfg_parts.len() == 1 {
            cfg_parts[0].clone()
        } else {
            format!("all({})", cfg_parts.join(", "))
        };
        writeln!(output, "    #[cfg({cfg})]").unwrap();
    }

    writeln!(output, "    #[test]").unwrap();
    writeln!(output, "    fn {fn_name}() {{").unwrap();

    // Create DB and load dataset. The persistent variant exercises the
    // WAL-wrapped store path that `GrafeoDB::open()` always produces, so
    // regressions in wrapper delegation (e.g. #308) fail here instead of
    // slipping past the in-memory-only suite.
    match db_source {
        DbSource::InMemory => {
            writeln!(output, "        let db = GrafeoDB::new_in_memory();").unwrap();
        }
        DbSource::Persistent => {
            writeln!(
                output,
                "        let _tmp = tempfile::tempdir().expect(\"tempdir for persistent spec test\");"
            )
            .unwrap();
            writeln!(
                output,
                "        let db = GrafeoDB::open(_tmp.path().join(\"spec.grafeo\")).expect(\"open persistent GrafeoDB for spec test\");"
            )
            .unwrap();
        }
    }

    let effective_dataset = tc.dataset.as_deref().unwrap_or(&file.meta.dataset);
    if effective_dataset != "empty" {
        let dataset_path = format!("tests/spec/datasets/{}.setup", effective_dataset);
        writeln!(
            output,
            "        load_dataset(&db, \"{}\");",
            escape_rust_string(&dataset_path)
        )
        .unwrap();
    }

    // Setup queries run in the file's declared language and model. This allows
    // SPARQL tests to use INSERT DATA in setup, Cypher tests to use CREATE, etc.
    // For rosetta variant tests, setup always uses meta.language (the file default).
    let setup_language = &file.meta.language;
    for setup_q in &tc.setup {
        writeln!(
            output,
            "        execute_query_with_model(&db, \"{}\", \"{}\", \"{}\");",
            escape_rust_string(setup_language),
            escape_rust_string(model),
            escape_rust_string(setup_q)
        )
        .unwrap();
    }

    // Determine the query to execute
    let query = query_override
        .map(String::from)
        .or_else(|| tc.query.clone());
    let queries = if !tc.statements.is_empty() {
        tc.statements.clone()
    } else if let Some(q) = &query {
        vec![q.clone()]
    } else {
        writeln!(
            output,
            "        panic!(\"No query or statements in test '{}' at {}\");",
            tc.name, rel_path
        )
        .unwrap();
        writeln!(output, "    }}").unwrap();
        writeln!(output).unwrap();
        return;
    };

    // Execute queries (all but last are fire-and-forget, last captures result)
    if queries.len() == 1 {
        generate_execute_and_assert(output, &queries[0], language, model, tc, false);
    } else {
        let has_params = !tc.params.is_empty();

        // Build params once before the loop so fire-and-forget statements
        // can use them too (e.g. INSERT/SET with $param).
        if has_params {
            generate_params_hashmap(output, tc);
        }

        // Execute all but last (with params so $param in INSERT/SET works)
        for q in &queries[..queries.len() - 1] {
            if has_params {
                writeln!(
                    output,
                    "        execute_query_result_with_params(&db, \"{}\", \"{}\", \"{}\", params.clone()).expect(\"setup statement failed\");",
                    escape_rust_string(language),
                    escape_rust_string(model),
                    escape_rust_string(q),
                )
                .unwrap();
            } else {
                writeln!(
                    output,
                    "        execute_query_with_model(&db, \"{}\", \"{}\", \"{}\");",
                    escape_rust_string(language),
                    escape_rust_string(model),
                    escape_rust_string(q)
                )
                .unwrap();
            }
        }
        // Last query: capture result and assert
        let last = &queries[queries.len() - 1];
        generate_execute_and_assert(output, last, language, model, tc, has_params);
    }

    writeln!(output, "    }}").unwrap();
    writeln!(output).unwrap();
}

fn generate_params_hashmap(output: &mut String, tc: &TestCase) {
    writeln!(output, "        let params = {{").unwrap();
    writeln!(
        output,
        "            let mut m = std::collections::HashMap::new();"
    )
    .unwrap();
    for (key, text) in &tc.params {
        let code = param_value_code(text)
            .unwrap_or_else(|e| panic!("test '{}', param '{key}': {e}", tc.name));
        writeln!(
            output,
            "            m.insert(\"{}\".to_string(), {code});",
            escape_rust_string(key)
        )
        .unwrap();
    }
    writeln!(output, "            m").unwrap();
    writeln!(output, "        }};").unwrap();
}

/// Rust code that builds the `Value` for a parameter, by the rule every runner
/// follows (this runner is the reference): a quoted value is a string, whatever
/// it reads like; a bare value starting with `[` or `{` is JSON; a bare decimal
/// integer that fits `i64` is an `Int64` and any other bare decimal number a
/// `Float64`; a bare `true` or `false` is a `Bool`; any other bare value is a
/// string. `inf`, `NaN`, `0x1F` and `1_000` are strings: none of them is a
/// decimal number.
fn param_value_code(param: &ParamText) -> Result<String, String> {
    const VALUE: &str = "grafeo_common::types::Value";
    let text = match param {
        ParamText::Quoted(text) => {
            return Ok(format!(
                "{VALUE}::String(\"{}\".into())",
                escape_rust_string(text)
            ));
        }
        ParamText::Bare(text) => text.trim(),
    };
    if text.starts_with('[') || text.starts_with('{') {
        return json_param_to_value_code(text);
    }
    if is_decimal_integer(text)
        && let Ok(n) = text.parse::<i64>()
    {
        return Ok(format!("{VALUE}::Int64({n})"));
    }
    if is_decimal_number(text) {
        let f: f64 = text
            .parse()
            .map_err(|e| format!("`{text}` is not a number: {e}"))?;
        if !f.is_finite() {
            return Err(format!("`{text}` is out of the f64 range"));
        }
        return Ok(format!("{VALUE}::Float64({f:?}_f64)"));
    }
    if text == "true" || text == "false" {
        return Ok(format!("{VALUE}::Bool({text})"));
    }
    Ok(format!(
        "{VALUE}::String(\"{}\".into())",
        escape_rust_string(text)
    ))
}

/// `[+-]?[0-9]+`: an integer as every runner reads it (no `_`, no hex prefix).
fn is_decimal_integer(text: &str) -> bool {
    let digits = text.strip_prefix(['+', '-']).unwrap_or(text);
    !digits.is_empty() && digits.bytes().all(|b| b.is_ascii_digit())
}

/// `[+-]?([0-9]+(\.[0-9]*)?|\.[0-9]+)([eE][+-]?[0-9]+)?`: a number as every
/// runner reads it. It leaves out the `inf`, `infinity` and `NaN` that
/// `f64::from_str` also accepts.
fn is_decimal_number(text: &str) -> bool {
    let all_digits = |s: &str| s.bytes().all(|b| b.is_ascii_digit());
    let unsigned = text.strip_prefix(['+', '-']).unwrap_or(text);
    let (mantissa, exponent) = match unsigned.find(['e', 'E']) {
        Some(at) => (&unsigned[..at], Some(&unsigned[at + 1..])),
        None => (unsigned, None),
    };
    let (whole, fraction) = mantissa.split_once('.').unwrap_or((mantissa, ""));
    let mantissa_ok =
        (!whole.is_empty() || !fraction.is_empty()) && all_digits(whole) && all_digits(fraction);
    let exponent_ok = exponent.is_none_or(|e| {
        let digits = e.strip_prefix(['+', '-']).unwrap_or(e);
        !digits.is_empty() && all_digits(digits)
    });
    mantissa_ok && exponent_ok
}

/// Rust code that builds the `Value` for a param written as a JSON list or map
/// (`[1, 2]`, `{"city": "Amsterdam", "tags": [1, 2]}`). The build script has no
/// JSON dependency, so this parses JSON values: lists, maps, strings, numbers,
/// `true`, `false` and `null`.
fn json_param_to_value_code(text: &str) -> Result<String, String> {
    let chars: Vec<char> = text.chars().collect();
    let mut pos = 0;
    let code = json_value_code(&chars, &mut pos)?;
    skip_json_whitespace(&chars, &mut pos);
    if pos == chars.len() {
        Ok(code)
    } else {
        Err(format!("text after the JSON value in `{text}`"))
    }
}

fn skip_json_whitespace(chars: &[char], pos: &mut usize) {
    while chars.get(*pos).is_some_and(|c| c.is_whitespace()) {
        *pos += 1;
    }
}

fn json_value_code(chars: &[char], pos: &mut usize) -> Result<String, String> {
    const VALUE: &str = "grafeo_common::types::Value";
    skip_json_whitespace(chars, pos);
    match chars.get(*pos) {
        Some('[') => {
            *pos += 1;
            let mut items = Vec::new();
            skip_json_whitespace(chars, pos);
            if chars.get(*pos) == Some(&']') {
                *pos += 1;
            } else {
                loop {
                    items.push(json_value_code(chars, pos)?);
                    skip_json_whitespace(chars, pos);
                    match chars.get(*pos) {
                        Some(',') => *pos += 1,
                        Some(']') => {
                            *pos += 1;
                            break;
                        }
                        _ => return Err(format!("expected ',' or ']' at {pos}")),
                    }
                }
            }
            Ok(format!(
                "{VALUE}::List(Vec::<{VALUE}>::from([{}]).into())",
                items.join(", ")
            ))
        }
        Some('{') => {
            *pos += 1;
            let mut entries = Vec::new();
            skip_json_whitespace(chars, pos);
            if chars.get(*pos) == Some(&'}') {
                *pos += 1;
            } else {
                loop {
                    skip_json_whitespace(chars, pos);
                    let key = json_string(chars, pos)?;
                    skip_json_whitespace(chars, pos);
                    if chars.get(*pos) != Some(&':') {
                        return Err(format!("expected ':' at {pos}"));
                    }
                    *pos += 1;
                    let value = json_value_code(chars, pos)?;
                    entries.push(format!(
                        "(grafeo_common::types::PropertyKey::new(\"{}\"), {value})",
                        escape_rust_string(&key)
                    ));
                    skip_json_whitespace(chars, pos);
                    match chars.get(*pos) {
                        Some(',') => *pos += 1,
                        Some('}') => {
                            *pos += 1;
                            break;
                        }
                        _ => return Err(format!("expected ',' or '}}' at {pos}")),
                    }
                }
            }
            Ok(format!(
                "{VALUE}::Map(std::sync::Arc::new(std::collections::BTreeMap::<grafeo_common::types::PropertyKey, {VALUE}>::from([{}])))",
                entries.join(", ")
            ))
        }
        Some('"') => {
            let text = json_string(chars, pos)?;
            Ok(format!(
                "{VALUE}::String(\"{}\".into())",
                escape_rust_string(&text)
            ))
        }
        Some(_) => {
            let start = *pos;
            while chars
                .get(*pos)
                .is_some_and(|c| c.is_alphanumeric() || matches!(c, '-' | '+' | '.'))
            {
                *pos += 1;
            }
            let word: String = chars[start..*pos].iter().collect();
            match word.as_str() {
                "true" | "false" => Ok(format!("{VALUE}::Bool({word})")),
                "null" => Ok(format!("{VALUE}::Null")),
                _ if is_json_number(&word) => {
                    if let Ok(n) = word.parse::<i64>() {
                        Ok(format!("{VALUE}::Int64({n})"))
                    } else {
                        match word.parse::<f64>() {
                            Ok(f) if f.is_finite() => Ok(format!("{VALUE}::Float64({f:?}_f64)")),
                            _ => Err(format!("`{word}` is out of the f64 range")),
                        }
                    }
                }
                _ => Err(format!("not a JSON value: `{word}`")),
            }
        }
        None => Err("unexpected end of the JSON value".to_string()),
    }
}

/// `-?(0|[1-9][0-9]*)(\.[0-9]+)?([eE][+-]?[0-9]+)?`: a JSON number. Stricter
/// than `is_decimal_number` (no `+`, no bare `.`, no leading zero), so a list
/// this runner accepts parses in every runner's JSON reader too.
fn is_json_number(word: &str) -> bool {
    let all_digits = |s: &str| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit());
    let unsigned = word.strip_prefix('-').unwrap_or(word);
    let (mantissa, exponent) = match unsigned.find(['e', 'E']) {
        Some(at) => (&unsigned[..at], Some(&unsigned[at + 1..])),
        None => (unsigned, None),
    };
    let (whole, fraction) = match mantissa.split_once('.') {
        Some((whole, fraction)) => (whole, Some(fraction)),
        None => (mantissa, None),
    };
    let whole_ok = all_digits(whole) && (whole == "0" || !whole.starts_with('0'));
    let fraction_ok = fraction.is_none_or(all_digits);
    let exponent_ok = exponent.is_none_or(|e| all_digits(e.strip_prefix(['+', '-']).unwrap_or(e)));
    whole_ok && fraction_ok && exponent_ok
}

/// Reads a JSON string starting at the opening quote.
fn json_string(chars: &[char], pos: &mut usize) -> Result<String, String> {
    if chars.get(*pos) != Some(&'"') {
        return Err(format!("expected a string at {pos}"));
    }
    *pos += 1;
    let mut text = String::new();
    loop {
        match chars.get(*pos) {
            None => return Err("unterminated JSON string".to_string()),
            Some('"') => {
                *pos += 1;
                return Ok(text);
            }
            Some('\\') => {
                let escaped = chars.get(*pos + 1).copied();
                *pos += 2;
                match escaped {
                    Some('"') => text.push('"'),
                    Some('\\') => text.push('\\'),
                    Some('/') => text.push('/'),
                    Some('n') => text.push('\n'),
                    Some('r') => text.push('\r'),
                    Some('t') => text.push('\t'),
                    Some('b') => text.push('\u{8}'),
                    Some('f') => text.push('\u{c}'),
                    Some('u') => text.push(json_unicode_escape(chars, pos)?),
                    _ => return Err(format!("bad escape at {pos}")),
                }
            }
            Some(&c) => {
                text.push(c);
                *pos += 1;
            }
        }
    }
}

/// Reads the four hex digits of a `\u` escape at `pos` (just past the `u`).
/// JSON writes a character outside the Basic Multilingual Plane as a UTF-16
/// surrogate pair (`\uD83C\uDF37`): a high surrogate must be followed by a
/// `\u` escape of a low one, and the two make one character.
fn json_unicode_escape(chars: &[char], pos: &mut usize) -> Result<char, String> {
    let high = json_hex4(chars, pos)?;
    let code = match high {
        0xD800..=0xDBFF => {
            if chars.get(*pos) != Some(&'\\') || chars.get(*pos + 1) != Some(&'u') {
                return Err(format!(
                    "\\u{high:04X} is a high surrogate without a low one after it"
                ));
            }
            *pos += 2;
            let low = json_hex4(chars, pos)?;
            if !(0xDC00..=0xDFFF).contains(&low) {
                return Err(format!(
                    "\\u{high:04X} is followed by \\u{low:04X}, not by a low surrogate"
                ));
            }
            0x10000 + ((high - 0xD800) << 10) + (low - 0xDC00)
        }
        0xDC00..=0xDFFF => {
            return Err(format!(
                "\\u{high:04X} is a low surrogate without a high one before it"
            ));
        }
        _ => high,
    };
    char::from_u32(code).ok_or_else(|| format!("\\u escape {code:X} is not a character"))
}

/// Reads four hex digits at `pos` and moves past them.
fn json_hex4(chars: &[char], pos: &mut usize) -> Result<u32, String> {
    let hex: String = chars.get(*pos..*pos + 4).unwrap_or(&[]).iter().collect();
    if hex.len() != 4 || !hex.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err(format!("bad \\u escape `{hex}`"));
    }
    *pos += 4;
    u32::from_str_radix(&hex, 16).map_err(|_| format!("bad \\u escape `{hex}`"))
}

fn generate_execute_and_assert(
    output: &mut String,
    query: &str,
    language: &str,
    model: &str,
    tc: &TestCase,
    params_already_emitted: bool,
) {
    let expect = &tc.expect;
    let has_params = !tc.params.is_empty();

    // Build params HashMap if test has parameters and not already emitted
    // (multi-statement tests emit params before the fire-and-forget loop).
    if has_params && !params_already_emitted {
        generate_params_hashmap(output, tc);
    }

    // Error case
    if let Some(err_substr) = &expect.error {
        if has_params {
            writeln!(
                output,
                "        let result = execute_query_result_with_params(&db, \"{}\", \"{}\", \"{}\", params);",
                escape_rust_string(language),
                escape_rust_string(model),
                escape_rust_string(query)
            )
            .unwrap();
        } else {
            writeln!(
                output,
                "        let result = execute_query_result(&db, \"{}\", \"{}\", \"{}\");",
                escape_rust_string(language),
                escape_rust_string(model),
                escape_rust_string(query)
            )
            .unwrap();
        }
        writeln!(
            output,
            "        assert!(result.is_err(), \"Expected error containing '{}' but query succeeded\");",
            escape_rust_string(err_substr)
        )
        .unwrap();
        writeln!(
            output,
            "        let err_msg = format!(\"{{}}\", result.unwrap_err());",
        )
        .unwrap();
        writeln!(
            output,
            "        assert!(err_msg.contains(\"{}\"), \"Error '{{}}' does not contain '{}'\", err_msg);",
            escape_rust_string(err_substr),
            escape_rust_string(err_substr)
        )
        .unwrap();
        return;
    }

    // Normal execution
    if has_params {
        writeln!(
            output,
            "        let result = execute_query_result_with_params(&db, \"{}\", \"{}\", \"{}\", params).expect(\"query failed\");",
            escape_rust_string(language),
            escape_rust_string(model),
            escape_rust_string(query)
        )
        .unwrap();
    } else {
        writeln!(
            output,
            "        let result = execute_query_result(&db, \"{}\", \"{}\", \"{}\").expect(\"query failed\");",
            escape_rust_string(language),
            escape_rust_string(model),
            escape_rust_string(query)
        )
        .unwrap();
    }

    // Column assertion (checked before value assertions)
    if !expect.columns.is_empty() {
        let cols: Vec<String> = expect
            .columns
            .iter()
            .map(|c| format!("\"{}\"", escape_rust_string(c)))
            .collect();
        writeln!(
            output,
            "        assert_columns(&result, &[{}]);",
            cols.join(", ")
        )
        .unwrap();
    }

    // Empty check
    if expect.empty {
        writeln!(
            output,
            "        assert_eq!(result.row_count(), 0, \"Expected empty result\");"
        )
        .unwrap();
        return;
    }

    // Count check
    if let Some(count) = expect.count {
        writeln!(
            output,
            "        assert_eq!(result.row_count(), {count}, \"Expected {count} row(s)\");"
        )
        .unwrap();
        return;
    }

    // Hash check
    if let Some(hash) = &expect.hash {
        writeln!(
            output,
            "        assert_hash(&result, \"{}\");",
            escape_rust_string(hash)
        )
        .unwrap();
        return;
    }

    // Rows check
    if !expect.rows.is_empty() {
        // Build expected rows literal
        writeln!(output, "        let expected: Vec<Vec<String>> = vec![").unwrap();
        for row in &expect.rows {
            let cols: Vec<String> = row
                .iter()
                .map(|c| {
                    if c.is_empty() {
                        "String::new()".to_string()
                    } else {
                        format!("\"{}\".to_string()", escape_rust_string(c))
                    }
                })
                .collect();
            writeln!(output, "            vec![{}],", cols.join(", ")).unwrap();
        }
        writeln!(output, "        ];").unwrap();

        if let Some(precision) = expect.precision {
            writeln!(
                output,
                "        assert_rows_with_precision(&result, &expected, {precision});"
            )
            .unwrap();
        } else if expect.ordered {
            writeln!(output, "        assert_rows_ordered(&result, &expected);").unwrap();
        } else {
            writeln!(output, "        assert_rows_sorted(&result, &expected);").unwrap();
        }
    }
}
