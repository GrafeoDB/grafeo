from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def test_zensical_replaces_mkdocs():
    assert (ROOT / "zensical.toml").exists()
    assert not (ROOT / "mkdocs.yml").exists()
    for gone in ["docs/overrides", "docs/hooks", "docs/requirements.txt"]:
        assert not (ROOT / gone).exists(), gone


def test_no_third_party_fonts_or_polyfill():
    text = (ROOT / "zensical.toml").read_text(encoding="utf-8")
    assert "polyfill.io" not in text and "fonts.googleapis" not in text
    assert "font = false" in text and "generator = false" in text


def test_identity_css_is_the_generated_template():
    ours = (ROOT / "docs/stylesheets/extra.css").read_bytes()
    assert (
        ours.startswith(b"/* Generated")
        or b"Generated by tokens/build.mjs" in ours[:400]
    )


def test_changelog_page_includes_the_root_changelog():
    page = next((ROOT / "docs").rglob("changelog.md"))
    assert page.read_text(encoding="utf-8").strip() == '--8<-- "CHANGELOG.md"'
